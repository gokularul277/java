public class switc {
    public static void main(String[] args) {
        char grade='0';
        switch(grade){
            case 'a':
                System.out.println("hi");
                break;

            case 'b':
                System.out.println("hi");
                break;

            case 'v':
                System.out.println("kjjhu");
                break;

            case 'j':
                System.out.println("sgfgf");
                break;

            default :
                System.out.println("ooo");
        }
    }
    
}
