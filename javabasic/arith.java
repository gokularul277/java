public class arith {
    public static void main(String[] args) {
        int a=10;
        int b=56;
        int c=a+b;
        int d=a-b;
        int e=a*b;
        float f=(float)a/(float)b;//type casting
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
        System.out.println(f);
    }
}
